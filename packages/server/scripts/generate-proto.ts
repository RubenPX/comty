import ts from 'typescript'
import fs from 'node:fs'
import path from 'node:path'
import { Analysis } from './proto-analysis'

// Static analysis only: never import handlers, connect to databases or execute schemas.
export type Field = { name: string; type: string; repeated?: boolean; optional?: boolean; note?: string }
export type Message = { name: string; fields: Field[]; source: string }
export type Rpc = { name: string; request: string; response: string; transport: string; source: string }
export type Service = { name: string; rpcs: Rpc[] }
export const identifier = (s: string) => {
  const value = s.replace(/[^a-zA-Z0-9_]/g, '_') || 'Root'
  return /^\d/.test(value) ? `N${value}` : value
}
export const title = (s: string) => identifier(s.split(/[^a-zA-Z0-9]+/).filter(Boolean).map(p => p[0].toUpperCase() + p.slice(1)).join(''))
export function walk(n: ts.Node, fn: (n: ts.Node) => void) { fn(n); ts.forEachChild(n, c => walk(c, fn)) }
export function files(root: string): string[] {
  if (!fs.existsSync(root)) return []
  return fs.readdirSync(root, { withFileTypes: true }).sort((a,b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)
    .flatMap(e => ['node_modules', '.git', 'build', 'dist'].includes(e.name) ? [] : e.isDirectory() ? files(path.join(root, e.name)) : /\.(ts|js)$/.test(e.name) && !e.name.endsWith('.d.ts') ? [path.join(root, e.name)] : [])
}
export type TagRegistry = Record<string, Record<string, { number: number; signature: string }>>
export function render(messages: Message[], services: Service[] = [], registry: TagRegistry = {}): string {
  const lines = ['// Generated by scripts/generate-proto.ts. Static contract, not a running gRPC server.', '// Preserve comty.tags.json: field numbers must never be reassigned.', 'syntax = "proto3";', 'package comty.v1;', 'import "google/protobuf/struct.proto";', 'import "google/protobuf/timestamp.proto";', 'import "google/protobuf/descriptor.proto";', '', '// Transport metadata for adapters; does not change the actual HTTP/WS/IPC server.', 'extend google.protobuf.MethodOptions {', '  string http_method = 51001;', '  string http_path = 51002;', '  string ws_event = 51003;', '  string source_file = 51005;', '}', '']
  for (const msg of messages) {
    if (!Object.hasOwn(registry, msg.name)) Object.defineProperty(registry, msg.name, { value: Object.create(null), enumerable: true, writable: true, configurable: true })
    const tags = registry[msg.name]
    let next = Math.max(0, ...Object.values(tags).map(f => f.number)) + 1
    for (const f of msg.fields) {
      const signature = `${f.repeated ? 'repeated ' : ''}${f.type}`
      if (Object.hasOwn(tags, f.name) && tags[f.name].signature !== signature) throw Error(`Incompatible protobuf field type: ${msg.name}.${f.name}: ${tags[f.name].signature} -> ${signature}. Version the contract explicitly.`)
      if (!Object.hasOwn(tags, f.name)) {
        if (next >= 19000 && next <= 19999) next = 20000
        if (next > 536870911) throw Error('Protobuf field number limit reached')
        Object.defineProperty(tags, f.name, { value: { number: next++, signature }, enumerable: true, writable: true, configurable: true })
      }
    }
    const current = new Set(msg.fields.map(f => f.name))
    const removed = Object.keys(tags).filter(k => !current.has(k))
    lines.push(`// Source: ${msg.source}`, `message ${msg.name} {`)
    if (removed.length) {
      lines.push(`  reserved ${removed.map(k => tags[k].number).sort((a,b) => a-b).join(', ')};`)
      lines.push(`  reserved ${removed.map(k => JSON.stringify(identifier(k))).join(', ')};`)
    }
    for (const f of [...msg.fields].sort((a,b) => tags[a.name].number - tags[b.name].number)) {
      if (f.note) lines.push(`  // ${f.note.replaceAll('\n', ' ')}`)
      const opts = identifier(f.name) === f.name && !f.name.includes('_') ? '' : ` [json_name = ${JSON.stringify(f.name)}]`
      const qualifier = f.type.startsWith('map<') ? '' : f.repeated ? 'repeated ' : f.optional ? 'optional ' : ''
      lines.push(`  ${qualifier}${f.type} ${identifier(f.name)} = ${tags[f.name].number}${opts};`)
    }
    lines.push('}', '')
  }
  for (const svc of services) {
    lines.push(`service ${svc.name} {`)
    for (const rpc of svc.rpcs) {
      lines.push(`  // ${rpc.transport}; Source: ${rpc.source}`, `  rpc ${rpc.name}(${rpc.request}) returns (${rpc.response}) {`, `    option (source_file) = ${JSON.stringify(rpc.source)};`)
      const http = rpc.transport.match(/^HTTP (\w+) (.*)$/)
      if (http) lines.push(`    option (http_method) = ${JSON.stringify(http[1])};`, `    option (http_path) = ${JSON.stringify(http[2])};`)
      else if (rpc.transport.startsWith('WS ')) lines.push(`    option (ws_event) = ${JSON.stringify(rpc.transport.slice(3))};`)
      lines.push('  }')
    }
    lines.push('}', '')
  }
  return lines.join('\n')
}
export function generate(root: string, registry: TagRegistry = {}) {
  const analysis = new Analysis(root).run()
  return { proto: render([...analysis.messages.values()], [...analysis.services.values()], registry), report: analysis.report(), registry }
}
if (import.meta.main) {
  try {
    const args = process.argv.slice(2)
    if (args.includes('--help')) {
      console.log('Usage: bun scripts/generate-proto.ts [--server-root DIR] [--out FILE.proto] [--tags FILE.json] [--check]')
      process.exit(0)
    }
    for (let i = 0; i < args.length; i++) {
      if (args[i] === '--check') continue
      if (!['--server-root', '--out', '--tags'].includes(args[i]) || !args[i+1] || args[i+1].startsWith('--')) throw Error('Invalid argument: ' + args[i])
      i++
    }
    const option = (name: string, fallback: string) => args.includes(name) ? args[args.indexOf(name) + 1] : fallback
    const root = path.resolve(option('--server-root', path.join(import.meta.dirname, '..')))
    const out = path.resolve(option('--out', path.join(root, 'docs/proto/comty.proto')))
    if (!out.endsWith('.proto')) throw Error('--out must end with .proto')
    const stem = out.slice(0, -6)
    const tags = path.resolve(option('--tags', stem + '.tags.json'))
    const registry: TagRegistry = fs.existsSync(tags) ? JSON.parse(fs.readFileSync(tags, 'utf8')) : {}
    const result = generate(root, registry)
    const artifacts = [[out, result.proto], [stem + '.coverage.json', JSON.stringify(result.report, null, 2) + '\n'], [tags, JSON.stringify(result.registry, null, 2) + '\n']]
    if (args.includes('--check')) {
      for (const [file, text] of artifacts) if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) throw Error('Stale or missing artifact: ' + file)
      console.log('Verified: proto, coverage and tag manifest are up to date.')
    } else {
      for (const [file, text] of artifacts) { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text) }
      console.log(`Generated ${out}\n${JSON.stringify(result.report.counts)}`)
    }
  } catch (error) { console.error(error instanceof Error ? error.message : error); process.exit(1) }
}
